#!/bin/bash
# Makes the big text fonts the screensaver's clock is drawn in, from Montserrat Medium
# (Debian's fonts-montserrat, SIL Open Font License 1.1: package/licences/OFL-1.1.txt), with
# scripts/icon-font.c, as LVGL fonts (4 bits a pixel):
#   src/font_clock_180.c  sprite_clock_180: the flaps' digits, 180 px
#   src/font_clock_56.c   sprite_clock_56: the date's number and month, 56 px (printable ASCII)
# Their output is committed, so building sprite needs neither the font nor FreeType. Run in
# Debian Trixie (docker run --rm -v "$PWD:/w" -w /w debian:trixie bash scripts/make-fonts.sh):
# it installs what it needs.
set -euo pipefail
cd "$(dirname "$0")/.."
export DEBIAN_FRONTEND=noninteractive
apt-get -qq update >/dev/null
apt-get -qq install -y --no-install-recommends fonts-montserrat gcc libc6-dev libfreetype-dev pkg-config >/dev/null
TTF=/usr/share/fonts/truetype/montserrat/Montserrat-Medium.ttf
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
cc -O2 -o "$work/icon-font" scripts/icon-font.c $(pkg-config --cflags --libs freetype2)
with_licence() {
	printf '/* Generated by scripts/make-fonts.sh: do not edit. Montserrat Medium (%s), Copyright 2011\n' "$(dpkg -s fonts-montserrat | sed -n 's/^Version: //p')"
	printf ' * The Montserrat Project Authors (https://github.com/JulietaUla/Montserrat), under the SIL\n'
	printf ' * Open Font License 1.1 (package/licences/OFL-1.1.txt). */\n\n'
	cat "$1"
}
"$work/icon-font" "$TTF" 180 sprite_clock_180 $(printf '%x ' $(seq 48 57)) > "$work/a.c"
with_licence "$work/a.c" > src/font_clock_180.c
"$work/icon-font" "$TTF" 56 sprite_clock_56 $(printf '%x ' $(seq 32 126)) > "$work/b.c"
with_licence "$work/b.c" > src/font_clock_56.c
ls -l src/font_clock_*.c
