// icon-font: renders glyphs from a TrueType font into an LVGL font (lv_font_fmt_txt, 4 bits a
// pixel, plain bitmaps), for sprite's tile icons. Used by make-icons.sh.
//   icon-font <font.ttf> <size px> <lvgl symbol> <codepoint>... > icons.c
// Codepoints are hex (e58a or 0xe58a). Only the glyphs asked for go in, so the font is small.
#include <ft2build.h>
#include FT_FREETYPE_H
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

struct glyph { unsigned cp; int w, h, ofs_x, ofs_y, adv; unsigned char *px; };

static int by_cp(const void *a, const void *b) {
	unsigned x = ((const struct glyph *)a)->cp, y = ((const struct glyph *)b)->cp;
	return x < y ? -1 : x > y;
}

int main(int argc, char **argv) {
	if (argc < 5) { fprintf(stderr, "usage: %s font.ttf size name codepoint...\n", argv[0]); return 2; }
	int size = atoi(argv[2]), n = argc - 4;
	const char *name = argv[3];
	FT_Library ft;
	FT_Face face;
	if (FT_Init_FreeType(&ft) || FT_New_Face(ft, argv[1], 0, &face) || FT_Set_Pixel_Sizes(face, 0, size)) {
		fprintf(stderr, "can't open %s at %d px\n", argv[1], size);
		return 1;
	}
	struct glyph *g = calloc(n, sizeof *g);
	for (int i = 0; i < n; i++) {
		g[i].cp = strtoul(argv[4 + i], NULL, 16);
		FT_UInt idx = FT_Get_Char_Index(face, g[i].cp);
		if (!idx || FT_Load_Glyph(face, idx, FT_LOAD_DEFAULT) || FT_Render_Glyph(face->glyph, FT_RENDER_MODE_NORMAL)) {
			fprintf(stderr, "no glyph for U+%04X\n", g[i].cp);
			return 1;
		}
		FT_GlyphSlot s = face->glyph;
		g[i].w = s->bitmap.width;
		g[i].h = s->bitmap.rows;
		g[i].ofs_x = s->bitmap_left;
		g[i].ofs_y = s->bitmap_top - (int)s->bitmap.rows; // the box's bottom, up from the baseline
		g[i].adv = (int)((s->advance.x * 16 + 32) >> 6);  // 1/16 px
		if (g[i].w > 255 || g[i].h > 255 || g[i].adv >= 4096) { fprintf(stderr, "U+%04X is too big\n", g[i].cp); return 1; }
		g[i].px = malloc(g[i].w * g[i].h + 1);
		for (int y = 0; y < g[i].h; y++)
			memcpy(g[i].px + y * g[i].w, s->bitmap.buffer + y * s->bitmap.pitch, g[i].w);
	}
	qsort(g, n, sizeof *g, by_cp);
	for (int i = 1; i < n; i++)
		if (g[i].cp == g[i - 1].cp) { fprintf(stderr, "U+%04X is listed twice\n", g[i].cp); return 1; }
	if (g[n - 1].cp - g[0].cp > 0xffff) { fprintf(stderr, "the codepoints span too far for one map\n"); return 1; }

	int asc = (int)(face->size->metrics.ascender >> 6), desc = (int)(-face->size->metrics.descender >> 6);
	printf("// Generated by scripts/icon-font.c (via make-icons.sh): do not edit.\n");
	printf("#include \"lvgl/lvgl.h\"\n\n");
	// Each glyph's pixels, 4 bits each, one row after another with no padding (stride 0).
	printf("static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {");
	size_t at = 0;
	unsigned *index = calloc(n, sizeof *index);
	for (int i = 0; i < n; i++) {
		index[i] = at;
		int count = g[i].w * g[i].h;
		for (int p = 0; p < count; p += 2) {
			unsigned hi = (g[i].px[p] + 8) / 17, lo = p + 1 < count ? (g[i].px[p + 1] + 8) / 17 : 0;
			if (at % 16 == 0) printf("\n\t");
			printf("0x%02x,", (hi << 4) | lo);
			at++;
		}
	}
	if (at >= (1u << 20)) { fprintf(stderr, "too many glyphs for one font\n"); return 1; }
	printf("\n};\n\n");
	printf("static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {\n");
	printf("\t{ .bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0 }, // id 0: none\n");
	for (int i = 0; i < n; i++)
		printf("\t{ .bitmap_index = %u, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d }, // U+%04X\n",
			index[i], g[i].adv, g[i].w, g[i].h, g[i].ofs_x, g[i].ofs_y, g[i].cp);
	printf("};\n\n");
	printf("static const uint16_t unicode_list[] = {");
	for (int i = 0; i < n; i++) printf("%s0x%x,", i % 12 ? " " : "\n\t", g[i].cp - g[0].cp);
	printf("\n};\n\n");
	printf("static const lv_font_fmt_txt_cmap_t cmaps[] = {\n");
	printf("\t{ .range_start = 0x%x, .range_length = %u, .glyph_id_start = 1, .unicode_list = unicode_list,\n",
		g[0].cp, g[n - 1].cp - g[0].cp + 1);
	printf("\t  .glyph_id_ofs_list = NULL, .list_length = %d, .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY },\n};\n\n", n);
	printf("static const lv_font_fmt_txt_dsc_t font_dsc = {\n");
	printf("\t.glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps, .kern_dsc = NULL,\n");
	printf("\t.kern_scale = 0, .cmap_num = 1, .bpp = 4, .kern_classes = 0, .bitmap_format = LV_FONT_FMT_TXT_PLAIN,\n};\n\n");
	printf("const lv_font_t %s = {\n", name);
	printf("\t.get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,\n");
	printf("\t.line_height = %d, .base_line = %d, .subpx = LV_FONT_SUBPX_NONE, .dsc = &font_dsc,\n};\n", asc + desc, desc);
	fprintf(stderr, "%d glyphs, %zu bytes of bitmaps\n", n, at);
	return 0;
}
