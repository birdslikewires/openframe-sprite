#!/usr/bin/env python3
# make-bird.py: src/bird.c, the firmware's boot logo (assets/bird.png: openframe-firmware's
# logo/logo-blw-pecking-bird-204x82.png, white on black) as an LVGL A8 image, its brightness
# as alpha, for Sprite's first frame (splash.c), which carries on from the boot splash. Plain
# Python, no libraries: python3 scripts/make-bird.py > src/bird.c
import os, struct, sys, zlib

src = os.path.join(os.path.dirname(__file__), '..', 'assets', 'bird.png')
d = open(src, 'rb').read()
assert d[:8] == b'\x89PNG\r\n\x1a\n'
w, h, depth, ctype = struct.unpack('>IIBB', d[16:26])
assert depth == 8 and ctype in (0, 2, 6), 'an 8-bit grey, RGB or RGBA PNG'
bpp = {0: 1, 2: 3, 6: 4}[ctype]
i, idat = 8, b''
while i < len(d):
    n, t = struct.unpack('>I4s', d[i:i + 8])
    if t == b'IDAT':
        idat += d[i + 8:i + 8 + n]
    i += 12 + n
raw, stride, p = zlib.decompress(idat), w * bpp, 0
prev, alpha = bytearray(stride), bytearray()
for y in range(h):
    f, line = raw[p], bytearray(raw[p + 1:p + 1 + stride])
    p += 1 + stride
    for x in range(stride):
        a = line[x - bpp] if x >= bpp else 0
        b, c = prev[x], (prev[x - bpp] if x >= bpp else 0)
        if f == 1: line[x] = (line[x] + a) & 255
        elif f == 2: line[x] = (line[x] + b) & 255
        elif f == 3: line[x] = (line[x] + (a + b) // 2) & 255
        elif f == 4:
            pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
            line[x] = (line[x] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
    for x in range(w):
        alpha.append(line[x * bpp])  # white on black: any channel is the brightness
    prev = line

out = sys.stdout
out.write('// Generated by scripts/make-bird.py from assets/bird.png: do not edit.\n')
out.write('#include "lvgl.h"\n\nstatic const uint8_t bird_px[%d] = {\n' % len(alpha))
for r in range(0, len(alpha), 24):
    out.write('\t' + ', '.join('0x%02x' % v for v in alpha[r:r + 24]) + ',\n')
out.write('};\n\nconst lv_image_dsc_t sprite_bird = {\n')
out.write('\t.header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = %d, .h = %d, .stride = %d },\n' % (w, h, w))
out.write('\t.data_size = sizeof bird_px,\n\t.data = bird_px,\n};\n')
