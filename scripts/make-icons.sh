#!/bin/bash
# Makes src/icons_40.c (the tile glyphs, a 40 px 4-bit LVGL font) and src/icons_table.h
# (their names, and the aliases) from the list in src/icons.txt, using Lucide's icon font;
# src/ui_icons.c and src/ui_icons.h, the few glyphs sprite's own screens use (UI_ICONS
# below), at 24 px; and puts Lucide's licence in src/icons-lucide-LICENSE.
# Run it after changing the list; its output is committed, so building sprite needs neither
# the font nor FreeType. It needs curl, python3, openssl, a C compiler and FreeType
# (pkg-config freetype2): scripts/icon-font.c renders the glyphs.
set -euo pipefail
cd "$(dirname "$0")/.."

LUCIDE=0.460.0
UI_ICONS="volume-2 sun wifi refresh-cw info power monitor monitor-off server microchip cpu memory-stick hard-drive network clock layout-grid package terminal clapperboard flask-conical" # Settings' tabs, then About's details
# npm's published integrity for that version (npm view lucide-static@0.460.0 dist.integrity)
LUCIDE_INTEGRITY=sha512-X6pIdg7jVxv7YQ/uR241hwhNiztcAfmj181TbcX7HCxxk/3mGaRtAc6b2ftUvQBufbJE6ehgyzO2uVsa604tWg==

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
curl -fsSL "https://registry.npmjs.org/lucide-static/-/lucide-static-${LUCIDE}.tgz" -o "$work/lucide.tgz"
[ "sha512-$(openssl dgst -sha512 -binary "$work/lucide.tgz" | openssl base64 -A)" = "$LUCIDE_INTEGRITY" ] ||
	{ echo "lucide-static ${LUCIDE} doesn't match npm's integrity for it" >&2; exit 1; }
tar xzf "$work/lucide.tgz" -C "$work" package/font/lucide.ttf package/font/info.json package/LICENSE

# The names (and aliases) to codepoints: the list for icon-font, and the table for sprite.
python3 -I - "$work/package/font/info.json" src/icons.txt "$work/range" src/icons_table.h "$LUCIDE" <<'PY'
import json, re, sys
info = json.load(open(sys.argv[1]))
names, aliases = [], []
for line in open(sys.argv[2]):
    line = line.split('#', 1)[0].strip()
    if not line:
        continue
    if '=' in line:
        a, n = (x.strip() for x in line.split('=', 1))
        aliases.append((a, n))
    else:
        names += line.split()
bad = [n for n in names + [n for _, n in aliases] if n not in info]
if bad:
    sys.exit('not in Lucide %s: %s' % (sys.argv[5], ' '.join(bad)))
if len(set(names)) != len(names):
    sys.exit('a name is listed twice')
cp = lambda n: int(info[n]['encodedCode'].lstrip('\\'), 16)
open(sys.argv[3], 'w').write(','.join('0x%x' % cp(n) for n in names))
with open(sys.argv[4], 'w') as f:
    f.write('// Generated by scripts/make-icons.sh from src/icons.txt (Lucide %s): do not edit.\n' % sys.argv[5])
    f.write('// The names apps\' manifests can give as icon=, and the glyph each is in icons_40.c.\n')
    f.write('static const struct { const char *name; uint32_t cp; } icon_names[] = {\n')
    for n in names:
        f.write('\t{ "%s", 0x%x },\n' % (n, cp(n)))
    for a, n in aliases:
        f.write('\t{ "%s", 0x%x }, // %s\n' % (a, cp(n), n))
    f.write('};\n')
print('%d icons, %d aliases' % (len(names), len(aliases)))
PY

# sprite's own glyphs: their codepoints, and a header naming each as a UTF-8 string.
python3 -I - "$work/package/font/info.json" "$work/ui-range" src/ui_icons.h "$LUCIDE" $UI_ICONS <<'PY'
import json, sys
info = json.load(open(sys.argv[1]))
names = sys.argv[5:]
bad = [n for n in names if n not in info]
if bad:
    sys.exit('not in Lucide %s: %s' % (sys.argv[4], ' '.join(bad)))
cp = lambda n: int(info[n]['encodedCode'].lstrip('\\'), 16)
open(sys.argv[2], 'w').write(' '.join('0x%x' % cp(n) for n in names))
with open(sys.argv[3], 'w') as f:
    f.write('// Generated by scripts/make-icons.sh (Lucide %s): do not edit.\n' % sys.argv[4])
    f.write('// The glyphs sprite\'s own screens use, in sprite_ui_24 (ui_icons.c), as UTF-8.\n')
    for n in names:
        c = cp(n)
        utf8 = bytes([0xe0 | (c >> 12), 0x80 | ((c >> 6) & 0x3f), 0x80 | (c & 0x3f)])
        f.write('#define UI_ICON_%s "%s"\n' % (n.upper().replace('-', '_'), ''.join('\\x%02x' % b for b in utf8)))
PY

cc -O2 -o "$work/icon-font" scripts/icon-font.c $(pkg-config --cflags --libs freetype2)
with_licence() {
	printf '/* Glyphs from Lucide %s (https://lucide.dev), under the ISC licence:\n *\n' "$LUCIDE"
	sed 's/^/ * /; s/ *$//' "$work/package/LICENSE"
	printf ' */\n\n'
	cat "$1"
}
"$work/icon-font" "$work/package/font/lucide.ttf" 40 sprite_icons_40 $(tr ',' ' ' < "$work/range") > "$work/f.c"
with_licence "$work/f.c" > src/icons_40.c
"$work/icon-font" "$work/package/font/lucide.ttf" 24 sprite_ui_24 $(cat "$work/ui-range") > "$work/f.c"
with_licence "$work/f.c" > src/ui_icons.c
cp "$work/package/LICENSE" src/icons-lucide-LICENSE # for the package's copyright file
ls -l src/icons_40.c src/icons_table.h src/ui_icons.c src/ui_icons.h
